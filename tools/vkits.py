def main():
    names, n, drum_kits = pool()
    out = []
    for kname, base, pads in VKITS:
        rows = []
        for p in pads:
            pitch, decay, filt, level, sample, punch, snap, crush = p
            ov = 0 if sample is None else ov_for(names[sample], n)
            rows.append(f"    {{{pitch}, {decay}, {filt}, {level}, {ov}, {punch}, {snap}, {crush}}}")
        out.append(f'    {{"{kname}", {drum_kits.index(base)}, {{\n' + ",\n".join(rows) + "}},")
    table = "static const vkit_t VKITS[%d] = {   /* generated by tools/vkits.py: a base kit + per-pad SAMPLE choices by name */\n" % len(VKITS) + "\n".join(out) + "\n};\n"
    s = CAT.read_text()
    s2 = re.sub(r"static const vkit_t VKITS\[\d+\] = \{.*?\n\};\n", table, s, flags=re.S)
    assert s2 != s or table in s
    CAT.write_text(s2)
    print(f"{len(VKITS)} built kits over {len(drum_kits)} sample kits ({', '.join(drum_kits)}), {n} samples")

if __name__ == "__main__":
    main()
