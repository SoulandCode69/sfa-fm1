"""The built kits (Cat's VKITS table in app/engine/cat.c): a base sample kit plus per-pad choices from the whole pool,
by name, so they survive any re-pack. Run after tools/pack_samples.py:  python3 tools/vkits.py
Pad params: PITCH DECAY FILTER LEVEL SAMPLE PUNCH SNAP CRUSH (SAMPLE: a 'KIT/NAME' or None for the base kit's pad)."""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "app" / "samples_data.c"
CAT = ROOT / "app" / "engine" / "cat.c"

def pool():
    s = SRC.read_text()
    smp = re.findall(r'\{(\d+), (\d+), (\d+), (\d+), "([^"]+)"\}', s)
    kits = re.findall(r'\{"([^"]+)", (\d+), (\d+), (\d)\}', s)
    names = {}
    for kname, first, n, is808 in kits:
        for i in range(int(n)):
            names[f"{kname}/{smp[int(first) + i][4]}"] = int(first) + i
    drum_kits = [k[0] for k in kits if k[3] == "0"]
    return names, len(smp), drum_kits

def ov_for(idx, n):
    for o in range(1, 128):
        if (o - 1) * n // 127 == idx: return o
    raise SystemExit(f"no SAMPLE value reaches {idx}")

D = (64, 127, 127, 100, None, 25, 0, 0)        # a plain pad
def pad(sample=None, pitch=64, decay=127, filt=127, level=100, punch=25, snap=0, crush=0):
    return (pitch, decay, filt, level, sample, punch, snap, crush)

