"""Pack assets/pack/<kit>/*.wav into app/samples_data.c: IMA ADPCM (4-bit) in the firmware image, read in place.
   kits: every folder but 808 is a drum kit of up to 16 pads (file order = pad order); 808/ holds the bass one-shots
   (root note from the _rNN suffix, default 36). Drums at 22.05 kHz, 808s at 11.025 kHz. Any folder of WAVs works:
   drop your own pack in (mono/stereo, any rate) and rebuild.
    python3 tools/pack_samples.py [--pack assets/pack] [--out app/samples_data.c]"""
import argparse, re, struct, wave
from pathlib import Path
import numpy as np

STEP = [7, 8, 9, 10, 11, 12, 13, 14, 16, 17, 19, 21, 23, 25, 28, 31, 34, 37, 41, 45, 50, 55, 60, 66, 73, 80, 88, 97, 107, 118,
        130, 143, 157, 173, 190, 209, 230, 253, 279, 307, 337, 371, 408, 449, 494, 544, 598, 658, 724, 796, 876, 963, 1060,
        1166, 1282, 1411, 1552, 1707, 1878, 2066, 2272, 2499, 2749, 3024, 3327, 3660, 4026, 4428, 4871, 5358, 5894, 6484,
        7132, 7845, 8630, 9493, 10442, 11487, 12635, 13899, 15289, 16818, 18500, 20350, 22385, 24623, 27086, 29794, 32767]
IDX = [-1, -1, -1, -1, 2, 4, 6, 8]

def adpcm_encode(pcm):
    pred, idx = 0, 0
    out = bytearray(); nib = []
    for s in pcm:
        step = STEP[idx]
        diff = int(s) - pred
        code = 0
        if diff < 0: code = 8; diff = -diff
        d = step >> 3
        if diff >= step: code |= 4; diff -= step; d += step
        if diff >= step >> 1: code |= 2; diff -= step >> 1; d += step >> 1
        if diff >= step >> 2: code |= 1; d += step >> 2
        pred = pred - d if code & 8 else pred + d
        pred = max(-32768, min(32767, pred))
        idx = max(0, min(88, idx + IDX[code & 7]))
        nib.append(code)
        if len(nib) == 2: out.append(nib[0] | nib[1] << 4); nib = []
    if nib: out.append(nib[0])
    return bytes(out)

def load(path, rate):
    w = wave.open(str(path)); ch, sw, sr, n = w.getnchannels(), w.getsampwidth(), w.getframerate(), w.getnframes()
    raw = w.readframes(n)
    if sw == 2: x = np.frombuffer(raw, "<i2").astype(float) / 32768
    elif sw == 1: x = (np.frombuffer(raw, "u1").astype(float) - 128) / 128
    elif sw == 3: b = np.frombuffer(raw, "u1").reshape(-1, 3); x = ((b[:, 0].astype(int) | b[:, 1].astype(int) << 8 | b[:, 2].astype(int) << 16) ^ 0x800000) - 0x800000; x = x / 8388608.0
    else: x = np.frombuffer(raw, "<i4").astype(float) / 2147483648
    x = x.reshape(-1, ch).mean(axis=1)
    if sr != rate:                                   # linear resample (the packs are already lowpassed)
        pos = np.arange(0, len(x) - 1, sr / rate); i = pos.astype(int); f = pos - i
        x = x[i] * (1 - f) + x[i + 1] * f
    # trim trailing silence below -54 dB, 8 ms fade
    env = np.abs(x); thr = 10 ** (-54 / 20) * max(env.max(), 1e-6)
    keep = np.nonzero(env > thr)[0]
    if len(keep): x = x[: min(len(x), keep[-1] + int(0.01 * rate))]
    n = min(len(x), int(0.008 * rate)); x[-n:] *= np.linspace(1, 0, n)
    peak = np.abs(x).max() or 1.0
    x = x * (0.89 / peak)                            # -1 dB: headroom is the engines' job
    return np.clip(x * 32767, -32768, 32767).astype(np.int16)

def main():
    ap = argparse.ArgumentParser()
    root = Path(__file__).resolve().parents[1]
    ap.add_argument("--pack", type=Path, default=root / "assets" / "pack")
    ap.add_argument("--out", type=Path, default=root / "app" / "samples_data.c")
    a = ap.parse_args()
    kits = sorted(p for p in a.pack.iterdir() if p.is_dir())
    data = bytearray(); table = []; kit_tab = []
    for kit in kits:
        is808 = kit.name.lower() in ("808", "reptile")      # the chromatic bass bank
        files = sorted(kit.glob("*.wav"))[:16]
        first = len(table)
        for f in files:
            low = is808 or any(k in f.stem.lower() for k in ("kick", "boom", "tom", "conga", "bongo", "tabla", "subdrop", "tek", "impact", "stab"))
            rate = 11025 if low else 22050               # low sounds at 11.025 kHz: half the flash, nothing lost
            pcm = load(f, rate)
            m = re.search(r"_r(\d+)", f.stem); rootn = int(m.group(1)) if m else 36
            name = re.sub(r"^\d+_", "", f.stem); name = re.sub(r"_r\d+$", "", name)[:12].upper()
            off = len(data)
            data += adpcm_encode(pcm)
            while len(data) & 3: data.append(0)
            table.append((off, len(pcm), rate, rootn, name))
        kit_tab.append((kit.name.upper()[:8], first, len(files), is808))
    with open(a.out, "w") as o:
        o.write("/* generated by tools/pack_samples.py from %s: IMA ADPCM 4-bit, in the image */\n" % a.pack.name)
        o.write('#include <stdint.h>\n#include "samples.h"\n')
        o.write("const uint8_t SMP_DATA[%d] = {\n" % len(data))
        for i in range(0, len(data), 24):
            o.write("    " + ",".join(str(b) for b in data[i:i + 24]) + ",\n")
        o.write("};\nconst smp_t SMP[%d] = {\n" % len(table))
        for off, n, rate, rootn, name in table:
            o.write('    {%d, %d, %d, %d, "%s"},\n' % (off, n, rate, rootn, name))
        o.write("};\nconst smpkit_t SMPKIT[%d] = {\n" % len(kit_tab))
        for name, first, n, is808 in kit_tab:
            o.write('    {"%s", %d, %d, %d},\n' % (name, first, n, int(is808)))
        o.write("};\nconst uint32_t SMP_N = %d, SMPKIT_N = %d;\n" % (len(table), len(kit_tab)))
    secs = sum(n / r for _, n, r, _, _ in table)
    print(f"{len(table)} samples, {len(kit_tab)} kits, {secs:.1f} s, {len(data) / 1024:.0f} KB -> {a.out}")
    for name, first, n, is808 in kit_tab: print(f"  {name:8s} {n:2d} samples" + (" (808, 11.025 kHz)" if is808 else ""))

if __name__ == "__main__":
    main()
