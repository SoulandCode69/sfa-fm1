#define NVKIT (sizeof VKITS / sizeof *VKITS)
static uint32_t smp_kits(void) { uint32_t i, n = 0; for (i = 0; i < SMPKIT_N; i++) if (!SMPKIT[i].is808) n++; return n; }
static uint32_t kit_count(void) { uint32_t n = smp_kits() + NVKIT; return n > MAXKITS ? MAXKITS : n; }
static const smpkit_t *smp_kit_at(uint32_t k) { uint32_t i, n = 0; for (i = 0; i < SMPKIT_N; i++) if (!SMPKIT[i].is808) { if (n == k) return &SMPKIT[i]; n++; } return &SMPKIT[0]; }
static const vkit_t *vkit_of(uint32_t k) { uint32_t s = smp_kits(); return k >= s && k - s < NVKIT ? &VKITS[k - s] : 0; }
static const smpkit_t *kit_at(uint32_t k) { const vkit_t *v = vkit_of(k); return smp_kit_at(v ? v->base : k); }
static const smp_t *pad_smp(uint32_t pad)
{
    const smpkit_t *k = kit_at(kit_i);
    uint32_t ov = pad_par[kit_i][pad][4];                 /* SAMPLE: 0 = the kit's own, else a sound from the whole pool */
    if (ov) { uint32_t idx = (ov - 1u) * SMP_N / 127u; return &SMP[idx >= SMP_N ? SMP_N - 1u : idx]; }
    return pad < k->n ? &SMP[k->first + pad] : 0;
}

uint8_t *cat_pad_blob(uint32_t *size) { *size = sizeof pad_par; return &pad_par[0][0][0]; }
const char *cat_pad_name(int pad) { const smp_t *s = pad >= 0 ? pad_smp((uint32_t)pad) : 0; return s ? s->name : "-"; }
const char *cat_kit_name(void) { const vkit_t *v = vkit_of(kit_i); return v ? v->name : kit_at(kit_i)->name; }
int cat_last_pad(void) { return last_pad; }
void cat_kit(int32_t step) { uint32_t n = kit_count(); kit_i = (uint8_t)(((int32_t)kit_i + step + (int32_t)n) % (int32_t)n); }
int cat_kit_index(void) { return kit_i; }
void cat_kit_set(int k) { uint32_t n = kit_count(); kit_i = (uint8_t)(k % (int)n); }
void cat_pads_default(void)
{
    /* kick kick2 snare rim clap chat ohat cym ltom mtom htom perc perc perc fx fx: hats and cymbals sit under the kicks */
    static const uint8_t LVL[NPADS] = {105, 105, 100, 85, 95, 72, 66, 62, 92, 92, 92, 80, 82, 70, 88, 100};
    static const uint8_t PUN[NPADS] = {40, 40, 35, 20, 30, 10, 10, 0, 25, 25, 25, 15, 15, 15, 0, 0};
    uint32_t k, p;
    for (k = 0; k < MAXKITS; k++) for (p = 0; p < NPADS; p++) {
        uint8_t *q = pad_par[k][p];
        const vkit_t *v = vkit_of(k);
        uint32_t i;
        if (v) { for (i = 0; i < PP; i++) q[i] = v->pad[p][i]; continue; }
        q[0] = 64; q[1] = 127; q[2] = 127; q[3] = LVL[p]; q[4] = 0; q[5] = PUN[p]; q[6] = p < 2u ? 20 : 0; q[7] = 0;
    }
}
static void pad_view_load(void) { uint32_t i; for (i = 0; i < NPARAM; i++) { par1[i] = pad_par[kit_i][shown_pad][i]; par1b[i] = pad_par[kit_i][shown_pad][4 + i]; } }
static void pad_view_store(void) { uint32_t i; for (i = 0; i < NPARAM; i++) { pad_par[kit_i][shown_pad][i] = par1[i]; pad_par[kit_i][shown_pad][4 + i] = par1b[i]; } }
static uint8_t shown_kit;
void cat_sync(void)                                     /* main loop, every frame: the pad pages' knobs are the pad's */
{
    if ((uint8_t)last_pad != shown_pad || shown_kit != kit_i) { shown_pad = (uint8_t)last_pad; shown_kit = kit_i; pad_view_load(); }
    else pad_view_store();
}

typedef struct { adpcm_t a; float env, dcoef, gain, inc, punch, snap, snap_lp, crushq; svf_t flt; svfc_t fc; uint8_t on, filt; } voice_t;
static voice_t v[NPADS];
static volatile uint8_t trig[NPADS], trig_vel[NPADS];
static float comp_env, comp_g = 1.0f, hp_x, hp_y;
static uint32_t rng = 7u;

static void c_init(void) { uint32_t i; for (i = 0; i < NPADS; i++) v[i].on = 0; comp_env = 0; pad_view_load(); }
static void c_panic(void) { c_init(); }

static void c_note(int32_t note, uint32_t vl, int on)
{
    if (!on || note < 0 || note >= NPADS) return;
    trig_vel[note] = (uint8_t)vl;
    trig[note] = 1;
    last_pad = (int8_t)note;
}

static void start(uint32_t p, float vel)
{
    const smp_t *s = pad_smp(p);
    voice_t *w = &v[p];
    const uint8_t *pp = pad_par[kit_i][p];
    float semis = ((float)pp[0] - 64.0f) * (24.0f / 127.0f) + ((float)par2[1] - 64.0f) * (12.0f / 127.0f);
    float dec = p01(pp[1]) * p01(par2[2]) * 2.0f, filt = p01(pp[2]);
    if (!s) return;
    if (p == 5u) v[6].on = 0;                                        /* the closed hat chokes the open one */
    adpcm_start(&w->a, s);
    w->inc = fm_exp2f(semis * (1.0f / 12.0f)) * ((float)s->rate / SR);
    w->env = 1.0f;
    w->dcoef = dec >= 1.99f ? 1.0f : decay_coef(0.01f + dec * dec * 0.6f);   /* DECAY 127 = the whole sample */
    w->gain = (0.2f + 0.8f * vel * vel) * p01(pp[3]) * 1.27f;          /* a velocity curve, the pad's level */
    w->punch = p01(pp[5]) * 2.0f;
    w->snap = p01(pp[6]) * 0.9f; w->snap_lp = 0.0f;
    w->crushq = pp[7] ? fm_exp2f(11.0f - p01(pp[7]) * 8.5f) : 0.0f;   /* 2048 .. 6 levels */
    w->filt = filt < 0.99f;
    if (w->filt) { svf_coef(&w->fc, 100.0f * fm_exp2f(filt * 7.2f), 0.1f); w->flt.ic1 = w->flt.ic2 = 0; }   /* 100 Hz .. 15 kHz */
    w->on = 1;
}

static void c_render(float *out, uint32_t n)
{
    uint32_t i, p;
    float comp = p01(par3[0]), punch = p01(par3[1]) * 1.5f, lowcut = p01(par3[2]), drive = p01(par3[3]);
    float level = p01(par2[3]) * 1.1f;
    float hpc = lowcut > 0.0f ? 1.0f - fm_exp2f(-6.2831853f * (20.0f + lowcut * 200.0f) / SR) : 0.0f;
    float thr = 1.0f - comp * 0.7f, slope = comp * 0.75f, makeup = 1.0f + comp * 0.6f;
    float dgain = 1.0f + drive * drive * 4.0f, dnorm = drive > 0.0f ? 1.0f / fm_soft(dgain * 0.7f) : 1.0f;
    for (p = 0; p < NPADS; p++)
        if (trig[p]) { trig[p] = 0; start(p, (float)trig_vel[p] * (1.0f / 127.0f)); }
    for (i = 0; i < n; i++) {
        float s = 0.0f, g;
        for (p = 0; p < NPADS; p++) {
            voice_t *w = &v[p];
            float x, pos;
            if (!w->on) continue;
            x = adpcm_read(&w->a, w->inc) * w->env * w->gain;
            pos = w->a.pos;
            if (w->filt) x = svf_lp(&w->flt, &w->fc, x);
            if (pos < 1800.0f) {                                                     /* the first 40 ms: PUNCH and SNAP */
                float lift = 1.0f - pos * (1.0f / 1800.0f);
                x *= 1.0f + (punch + w->punch) * lift * lift;
                if (w->snap > 0.0f && pos < 140.0f) {                                    /* SNAP: a bright 3 ms tick (highpassed noise) */
                    float nz = noise(&rng); w->snap_lp += (nz - w->snap_lp) * 0.35f;
                    x += (nz - w->snap_lp) * w->snap * w->gain * (1.0f - pos * (1.0f / 140.0f));
                }
            }
            if (w->crushq > 0.0f) x = (float)(int32_t)(x * w->crushq) / w->crushq;
            w->env *= w->dcoef;
            s += x;
            if (adpcm_done(&w->a) || w->env < 0.001f) w->on = 0;
        }
        if (hpc > 0.0f) { float y = s - hp_x + (1.0f - hpc) * hp_y; hp_x = s; hp_y = y; s = y; }   /* LOWCUT: a highpass */
        /* bus compressor: peak follower, fast attack, 120 ms release, soft knee; the gain every 8 samples */
        {
            float a = fm_fabsf(s);
            comp_env += (a > comp_env ? 0.4f : 0.0002f) * (a - comp_env);
            if ((i & 7u) == 0u) comp_g = comp_env > thr ? fm_powf(comp_env / thr, -slope) : 1.0f;
            g = comp_g;
            s *= g * makeup;
        }
        if (drive > 0.0f) s = fm_soft(s * 0.7f * dgain) * dnorm;
        s *= level;
        if (s > 1.5f) s = 1.5f; else if (s < -1.5f) s = -1.5f;        /* the ceiling (the master limits) */
        out[i] += s;
    }
}

static const char *c_text(uint8_t page, uint32_t p, char *buf)
{
    if (page == 2u && p == 0u) return cat_kit_name();
    if (page == 0u && p == 0u) { int32_t st = ((int32_t)par1[0] - 64) * 24 / 127; buf[0] = st < 0 ? '-' : '+'; st = st < 0 ? -st : st; buf[1] = (char)('0' + st / 10); buf[2] = (char)('0' + st % 10); buf[3] = 0; return buf; }
    if (page == 0u && p == 1u && par1[1] >= 127u) return "FULL";
    if (page == 0u && p == 2u && par1[2] >= 126u) return "OPEN";
    if (page == 1u && p == 0u) return par1b[0] ? cat_pad_name(shown_pad) : "KIT";
    if (page == 1u && p > 0u && par1b[p] == 0u) return "OFF";
    if (page == 3u && (p == 2u || p == 3u) && (p == 2u ? par3[2] : par3[3]) == 0u) return "OFF";
    return 0;
}

